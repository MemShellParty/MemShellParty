import { Tabs as TabsPrimitive } from "@base-ui/react/tabs";
import { cva, type VariantProps } from "class-variance-authority";
import { type Ref, useCallback, useEffect, useRef } from "react";

import { cn } from "@/lib/utils";

function scrollTabIntoView(trigger: Element | null | undefined) {
  if (trigger instanceof HTMLElement) {
    trigger.scrollIntoView({
      block: "nearest",
      inline: "nearest",
      container: "nearest",
    } as ScrollIntoViewOptions & { container: "nearest" });
  }
}

function Tabs({
  className,
  orientation = "horizontal",
  onValueChange,
  value,
  ref,
  ...props
}: TabsPrimitive.Root.Props) {
  const rootRef = useRef<HTMLDivElement | null>(null);
  const setRootRef = useCallback(
    (node: HTMLDivElement | null) => {
      rootRef.current = node;
      if (typeof ref === "function") ref(node);
      else if (ref)
        (ref as Ref<HTMLDivElement> & { current: HTMLDivElement | null }).current = node;
    },
    [ref],
  );

  useEffect(() => {
    if (value === undefined) return;
    const frame = requestAnimationFrame(() => {
      scrollTabIntoView(
        rootRef.current?.querySelector(
          ':scope > [data-slot="tabs-list"] > [data-slot="tabs-trigger"][data-active]',
        ),
      );
    });
    return () => cancelAnimationFrame(frame);
  }, [value]);

  return (
    <TabsPrimitive.Root
      data-slot="tabs"
      data-orientation={orientation}
      className={cn("group/tabs flex gap-2 data-[orientation=horizontal]:flex-col", className)}
      value={value}
      ref={setRootRef}
      onValueChange={(value, eventDetails) => {
        scrollTabIntoView(eventDetails.trigger);
        onValueChange?.(value, eventDetails);
      }}
      {...props}
    />
  );
}

const tabsListVariants = cva(
  "rounded-lg p-[3px] group-data-horizontal/tabs:h-9 data-[variant=line]:rounded-none group/tabs-list text-muted-foreground inline-flex w-fit max-w-full items-center justify-start overflow-x-auto group-data-[orientation=vertical]/tabs:h-fit group-data-[orientation=vertical]/tabs:flex-col group-data-[orientation=vertical]/tabs:overflow-x-visible",
  {
    variants: {
      variant: {
        default: "bg-muted",
        line: "gap-1 bg-transparent",
      },
    },
    defaultVariants: {
      variant: "default",
    },
  },
);

function TabsList({
  className,
  variant = "default",
  ...props
}: TabsPrimitive.List.Props & VariantProps<typeof tabsListVariants>) {
  return (
    <TabsPrimitive.List
      data-slot="tabs-list"
      data-variant={variant}
      className={cn(tabsListVariants({ variant }), className)}
      {...props}
    />
  );
}

